// Esquema. Todas las tablas llevan user_id: un solo usuario hoy, varios después sin migrar datos.
export const SCHEMA: string[] = [
  `create table if not exists users (
     id uuid primary key default gen_random_uuid(),
     email text unique not null,
     name text not null,
     base_currency text not null default 'AUD',
     paused boolean not null default false,
     demo boolean not null default false,
     created_at timestamptz not null default now())`,
  `create table if not exists accounts (
     id uuid primary key default gen_random_uuid(),
     user_id uuid not null references users(id) on delete cascade,
     name text not null,
     kind text not null,
     zone text not null,
     currency text not null,
     asset_class text not null,
     purpose text not null default '',
     connection text not null default 'Manual',
     created_at timestamptz not null default now(),
     unique (user_id, name))`,
  `create table if not exists balances (
     id uuid primary key default gen_random_uuid(),
     user_id uuid not null references users(id) on delete cascade,
     account_id uuid not null references accounts(id) on delete cascade,
     native_amount numeric,
     base_amount numeric not null,
     as_of timestamptz not null default now(),
     source text not null default 'manual')`,
  `create index if not exists balances_latest on balances (account_id, as_of desc)`,
  `create table if not exists liabilities (
     id uuid primary key default gen_random_uuid(),
     user_id uuid not null references users(id) on delete cascade,
     name text not null, zone text not null, base_amount numeric not null, note text not null default '')`,
  `create table if not exists transactions (
     id uuid primary key default gen_random_uuid(),
     user_id uuid not null references users(id) on delete cascade,
     account_id uuid not null references accounts(id) on delete cascade,
     posted_on text not null,
     amount numeric not null,
     currency text not null default 'AUD',
     description text not null default '',
     category text not null default '',
     kind text not null check (kind in ('income','expense','transfer','tax_reserve')),
     essential boolean not null default false,
     external_id text not null,
     created_at timestamptz not null default now(),
     unique (user_id, account_id, external_id))`,
  `create table if not exists net_worth_history (
     user_id uuid not null references users(id) on delete cascade,
     month text not null, net numeric not null, contributions numeric not null,
     primary key (user_id, month))`,
  `create table if not exists agents (
     id uuid primary key default gen_random_uuid(),
     user_id uuid not null references users(id) on delete cascade,
     code text not null, name text not null, objective text not null,
     data text not null, deliverables text not null, permissions text not null,
     kpi text not null, depends_on text not null, escalation text not null, cost_note text not null,
     implemented boolean not null default false,
     unique (user_id, code))`,
  `create table if not exists agent_runs (
     id uuid primary key default gen_random_uuid(),
     user_id uuid not null references users(id) on delete cascade,
     agent_id uuid not null references agents(id) on delete cascade,
     status text not null check (status in ('prog','run','wait','appr','done','err')),
     task text not null, result text not null default '',
     started_at timestamptz not null default now(),
     finished_at timestamptz, next_run_at timestamptz, next_note text)`,
  `create index if not exists runs_latest on agent_runs (agent_id, started_at desc)`,
  `create table if not exists proposals (
     id uuid primary key default gen_random_uuid(),
     user_id uuid not null references users(id) on delete cascade,
     agent_code text not null,
     level text not null check (level in ('urg','rev','sum','idea')),
     title text not null, evidence text not null, benefit text not null,
     effort text not null, risk text not null, next_step text not null,
     status text not null default 'pending' check (status in ('pending','approved','rejected','postponed')),
     created_at timestamptz not null default now(), resolved_at timestamptz)`,
  `create table if not exists events (
     id uuid primary key default gen_random_uuid(),
     user_id uuid not null references users(id) on delete cascade,
     at timestamptz not null default now(),
     actor text not null, action text not null, result text not null default '')`,
  `create table if not exists fiscal_items (
     id uuid primary key default gen_random_uuid(),
     user_id uuid not null references users(id) on delete cascade,
     due text not null, zone text not null, title text not null,
     status text not null default 'prog')`,
  `create table if not exists fx_rates (
     user_id uuid not null references users(id) on delete cascade,
     currency text not null, per_base numeric not null,
     primary key (user_id, currency))`,
];
